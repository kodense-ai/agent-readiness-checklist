import sys
import json
from datetime import datetime

PILLARS = [
    {
        "category": "Value & Economics",
        "weight": 6,
        "questions": [
            ("Volume Threshold", "Does the target workflow consume 20+ hours weekly across the team?"),
            ("Target Metric", "Is there a clearly defined quantitative metric tracked in software?"),
            ("Baseline Data", "Is there at least 14 days of audited pre-deployment baseline data?")
        ]
    },
    {
        "category": "Workflow Determinism",
        "weight": 6,
        "questions": [
            ("Process Structure", "Is there a documented SOP with defined branch rules?"),
            ("Execution Ratio", "Do 70%+ of tasks rely on deterministic rules rather than creative judgment?"),
            ("Observable Done State", "Is task completion recorded via an unambiguous software state change?")
        ]
    },
    {
        "category": "Systems & Data Access",
        "weight": 6,
        "questions": [
            ("API Availability", "Are programmatic REST/GraphQL APIs or database connections available?"),
            ("Historical Logs", "Are there 500+ historical completed transactions for evaluation?"),
            ("Credential Velocity", "Can service credentials and environment access be granted in under 14 days?")
        ]
    },
    {
        "category": "Governance & Safety",
        "weight": 8,
        "questions": [
            ("Workflow Owner", "Is there a designated operational owner with decision authority?"),
            ("Frontline Alignment", "Do operational teams view automation as leverage rather than a threat?"),
            ("Security Reviewer", "Is an assigned security engineer available to review data flows?"),
            ("Human Approval Gates", "Are explicit human approval gates defined for high-risk actions?")
        ]
    }
]

def run_assessment():
    print("=" * 60)
    print("  Kodense ARM-26: Enterprise AI Agent Readiness Assessment")
    print("  Reference: https://kodense.ai/blog/ai-agent-readiness-checklist/")
    print("=" * 60)
    print("\nScore each criterion: 0 (No), 1 (Partially), or 2 (Fully Verified)\n")

    scores = []
    total_score = 0

    for pillar in PILLARS:
        print(f"\n--- Pillar: {pillar['category']} (Max {pillar['weight']} pts) ---")
        cat_score = 0
        for title, q in pillar["questions"]:
            while True:
                try:
                    val = input(f"  [{title}] {q} [0/1/2]: ").strip()
                    score = int(val)
                    if score in (0, 1, 2):
                        cat_score += score
                        scores.append({"category": pillar["category"], "item": title, "score": score})
                        break
                    print("    Invalid input. Please enter 0, 1, or 2.")
                except ValueError:
                    print("    Invalid input. Please enter 0, 1, or 2.")
                except (KeyboardInterrupt, EOFError):
                    print("\nAssessment aborted.")
                    sys.exit(0)
        total_score += cat_score

    print("\n" + "=" * 60)
    print(f"  FINAL SCORE: {total_score} / 26 POINTS")
    print("=" * 60)

    if total_score >= 20:
        tier = "Tier-1 Production Candidate"
        action = "Workflow is ready for autonomous agent engineering sprint."
    elif total_score >= 12:
        tier = "Targeted Preparation Required"
        action = "Address data baseline, API connectivity, or approval gate gaps before building."
    else:
        tier = "Foundational Remediation Required"
        action = "Process is currently unsuited for autonomous agents. Fix process maturity first."

    print(f"\nClassification: {tier}")
    print(f"Recommended Action: {action}\n")

    # Export markdown report
    report_filename = f"arm26-report-{datetime.now().strftime('%Y%m%d-%H%M')}.md"
    with open(report_filename, "w", encoding="utf-8") as f:
        f.write(f"# ARM-26 AI Agent Readiness Report\n\n")
        f.write(f"- **Date:** {datetime.now().strftime('%Y-%m-%d %H:%M')}\n")
        f.write(f"- **Score:** {total_score} / 26\n")
        f.write(f"- **Classification:** {tier}\n")
        f.write(f"- **Action:** {action}\n\n")
        f.write("## Detailed Item Breakdown\n\n")
        for item in scores:
            f.write(f"- **{item['category']} // {item['item']}:** {item['score']} / 2\n")
        f.write(f"\n---\n*Generated by Kodense ARM-26 CLI (https://kodense.ai)*\n")

    print(f"Saved evaluation report to: {report_filename}")

if __name__ == "__main__":
    run_assessment()
